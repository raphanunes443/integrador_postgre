-- Trigger equivalente ao ON UPDATE CURRENT_TIMESTAMP do MySQL para recessos.
CREATE OR REPLACE FUNCTION atualizar_data_atualizacao_recessos()
RETURNS TRIGGER AS $$
BEGIN
    NEW.data_atualizacao = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

